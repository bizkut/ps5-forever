#!/usr/bin/env python3
"""Generate the title menu's deterministic Noto Sans alpha glyph tables."""
import argparse
import hashlib
from pathlib import Path
import tempfile
import urllib.request

from PIL import Image, ImageDraw, ImageFont

COMMIT = 'ffebf8c1ee449e544955a7e813c54f9b73848eac'
ROOT = f'https://raw.githubusercontent.com/notofonts/noto-fonts/{COMMIT}/hinted/ttf'
BASE = f'{ROOT}/NotoSans'
FONTS = {
    'regular': (f'{BASE}/NotoSans-Regular.ttf',
                'b85c38ecea8a7cfb39c24e395a4007474fa5a4fc864f6ee33309eb4948d232d5', 30),
    'bold': (f'{BASE}/NotoSans-Bold.ttf',
             'c976e4b1b99edc88775377fcc21692ca4bfa46b6d6ca6522bfda505b28ff9d6a', 40),
    'symbols': (f'{ROOT}/NotoSansSymbols2/NotoSansSymbols2-Regular.ttf',
                '630846d528dbe4c4981370a4d0a9475a1fd1491a129bb411f8e157cdb5de13c6', 30),
}
CODEPOINTS = [*range(32, 127), 0x2014, 0x2019, 0x2022, 0x2026, 0x2192,
              0x25A1, 0x25B3, 0x25CB, 0x2715]


def checked_font(kind, supplied, temporary):
    url, expected, _size = FONTS[kind]
    path = Path(supplied) if supplied else Path(temporary) / f'NotoSans-{kind}.ttf'
    if not supplied:
        urllib.request.urlretrieve(url, path)
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != expected:
        raise SystemExit(f'{kind} font SHA-256 {actual}, expected {expected}')
    return path


def rasterize(path, size, symbols_path):
    font = ImageFont.truetype(path, size)
    symbols = ImageFont.truetype(symbols_path, size)
    ascent, descent = font.getmetrics()
    glyphs, coverage = [], bytearray()
    for codepoint in CODEPOINTS:
        character = chr(codepoint)
        glyph_font = symbols if codepoint in (0x2192, 0x25A1, 0x25B3, 0x25CB, 0x2715) else font
        left, top, right, bottom = glyph_font.getbbox(character, anchor='ls')
        width, height = max(0, right - left), max(0, bottom - top)
        offset = len(coverage)
        if width and height:
            image = Image.new('L', (width, height), 0)
            ImageDraw.Draw(image).text(
                (-left, -top), character, font=glyph_font, fill=255, anchor='ls')
            coverage.extend(image.tobytes())
        glyphs.append((codepoint, offset, width, height, left, top,
                       int(glyph_font.getlength(character) + 0.5)))
    return ascent, descent, glyphs, bytes(coverage)


def rows(values, width=24):
    return '\n'.join('    ' + ', '.join(str(value) for value in values[at:at + width]) + ','
                     for at in range(0, len(values), width))


def emit_font(name, result):
    ascent, descent, glyphs, coverage = result
    records = '\n'.join(
        f'    {{{codepoint}u, {offset}u, {width}u, {height}u, {left}, {top}, {advance}u}},'
        for codepoint, offset, width, height, left, top, advance in glyphs)
    return f'''#define FOREVER_FONT_{name.upper()}_ASCENT {ascent}
#define FOREVER_FONT_{name.upper()}_DESCENT {descent}
static const struct forever_raster_glyph forever_font_{name}_glyphs[] = {{
{records}
}};
static const uint8_t forever_font_{name}_coverage[] = {{
{rows(coverage)}
}};
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--regular')
    parser.add_argument('--bold')
    parser.add_argument('--symbols')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='forever-menu-font-') as temporary:
        regular = checked_font('regular', args.regular, temporary)
        bold = checked_font('bold', args.bold, temporary)
        symbols = checked_font('symbols', args.symbols, temporary)
        generated = '''/* Generated by tools/make-menu-font.py from Noto Sans (OFL-1.1).
 * Licence: ps5/release/licenses/fonts/NotoSans-LICENSE. */
#ifndef PS5_TITLE_MENU_FONT_H
#define PS5_TITLE_MENU_FONT_H
#include <stdint.h>
struct forever_raster_glyph
{
    uint32_t codepoint, offset;
    uint16_t width, height;
    int16_t left, top;
    uint16_t advance;
};
'''
        generated += emit_font(
            'regular', rasterize(regular, FONTS['regular'][2], symbols))
        generated += emit_font('bold', rasterize(bold, FONTS['bold'][2], symbols))
        generated += '#endif\n'
        args.output.write_text(generated)


if __name__ == '__main__':
    main()
